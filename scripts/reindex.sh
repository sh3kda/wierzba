RECURSIVE=false
CREATE_NEW=false
FORCE=false
HAS_TARGET=false
TARGET_INPUT='.'
EXCLUDE_INPUTS=()
EXCLUDED_DIRS=()
while (($# > 0)); do
    case "$1" in
        --recursive|-r) RECURSIVE=true ;;
        --new) CREATE_NEW=true ;;
        --exclude)
            (($# >= 2)) || die "Opcja --exclude wymaga sciezki."
            [[ -n "$2" && "$2" != -* ]] || die "Podaj sciezke po --exclude; nazwy zaczynajace sie od - poprzedz ./."
            EXCLUDE_INPUTS+=("$2")
            shift
            ;;
        --force) FORCE=true ;;
        --help|-h) usage; exit 0 ;;
        --)
            shift
            [[ $# -eq 1 && "$HAS_TARGET" == false ]] || die "Po -- podaj dokladnie jeden folder."
            TARGET_INPUT="$1"
            HAS_TARGET=true
            break
            ;;
        -*) die "Nieznana opcja: $1. Uzyj --help." ;;
        *)
            [[ "$HAS_TARGET" == false ]] || die "Podaj tylko jeden folder."
            TARGET_INPUT="$1"
            HAS_TARGET=true
            ;;
    esac
    shift
done
[[ -n "$TARGET_INPUT" ]] || die "Sciezka folderu nie moze byc pusta."
[[ "$CREATE_NEW" != true || "$RECURSIVE" != true ]] || die "Wybierz --new albo --recursive."
[[ "$CREATE_NEW" != true || "$HAS_TARGET" == true ]] || die "Opcja --new wymaga nazwy folderu."
if ((${#EXCLUDE_INPUTS[@]} > 0)); then
    for excluded in "${EXCLUDE_INPUTS[@]}"; do
        resolve_project_path "$excluded"
        EXCLUDED_DIRS+=("$RESOLVED_PATH")
    done
fi
resolve_project_path "$TARGET_INPUT"
TARGET_DIR="$RESOLVED_PATH"
is_public_directory "$TARGET_DIR" || die "Folder techniczny lub ukryty: $TARGET_INPUT"
if [[ "$RECURSIVE" == false ]] && is_excluded_directory "$TARGET_DIR"; then
    die "Katalog chroniony przez .noindex lub --exclude: $TARGET_DIR"
fi

DIRECTORIES=()
if [[ "$CREATE_NEW" == true ]]; then
    [[ ! -e "$TARGET_DIR" ]] || die "Folder juz istnieje: $TARGET_DIR"
    directory="$TARGET_DIR"
    while :; do
        DIRECTORIES+=("$directory")
        [[ "$directory" != "$PROJECT_ROOT" ]] || break
        directory="${directory%/*}"
    done
else
    [[ -d "$TARGET_DIR" ]] || die "Folder nie istnieje: $TARGET_DIR"
    if [[ "$RECURSIVE" == true ]]; then
        collect_directories "$TARGET_DIR"
    else
        DIRECTORIES+=("$TARGET_DIR")
    fi
fi

if ((${#DIRECTORIES[@]} == 0)); then
    printf 'Brak katalogow do aktualizacji po zastosowaniu wykluczen.\n'
    exit 0
fi
for directory in "${DIRECTORIES[@]}"; do
    validate_output "$directory"
done
for asset in index.css index.js; do
    [[ -f "$PROJECT_ROOT/dh/web/media/$asset" ]] || die "Brak zasobu: dh/web/media/$asset"
done
if stat -c '%s' "$SCRIPT_DIR/reindex.sh" >/dev/null 2>&1; then
    STAT_STYLE=gnu
else
    STAT_STYLE=bsd
    stat -f '%z' "$SCRIPT_DIR/reindex.sh" >/dev/null
fi
if [[ "$CREATE_NEW" == true ]]; then
    (umask 022; mkdir -p -- "$TARGET_DIR")
fi

for directory in "${DIRECTORIES[@]}"; do
    TEMP_FILE="$(mktemp "$directory/.index.html.XXXXXX")"
    render_index "$directory" > "$TEMP_FILE"
    chmod 644 "$TEMP_FILE"
    mv -f -- "$TEMP_FILE" "$directory/index.html"
    TEMP_FILE=''
    printf 'Zaktualizowano: %s/index.html\n' "$directory"
done
