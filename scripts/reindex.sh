#!/usr/bin/env bash
set -euo pipefail
export LC_ALL=C
shopt -s nullglob
shopt -u dotglob failglob

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
PROJECT_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd -P)"
PERSONAL_ROOT="$PROJECT_ROOT/dh"
MARKER='<!-- Generated by scripts/reindex.sh; manual changes will be overwritten. -->'
LINKS_START_PATTERN='^[[:space:]]*<!-- DYNAMIC_LINKS_START -->[[:space:]]*$'
LINKS_END_PATTERN='^[[:space:]]*<!-- DYNAMIC_LINKS_END -->[[:space:]]*$'
TEMP_FILE=''

cleanup() {
    if [[ -n "$TEMP_FILE" ]]; then
        rm -f -- "$TEMP_FILE"
    fi
}

trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

die() {
    printf 'Blad: %s\n' "$*" >&2
    exit 1
}

usage() {
    cat <<'HELP'
Uzycie:
  bash scripts/reindex.sh [--recursive] [--exclude sciezka] [--force] [--] [folder]
  bash scripts/reindex.sh --new [--exclude sciezka] [--force] [--] folder

  --recursive, -r  Indeksuj rowniez wszystkie publiczne podkatalogi.
  --exclude       Pomin wskazany katalog i jego podkatalogi; mozna powtarzac.
  --new           Utworz nowy folder i odswiez indeksy wszystkich rodzicow.
  --force         Pozwol zastapic zwykly indeks, ale nie strone glowna
                  ani katalogi chronione przez .noindex lub --exclude.
  --help, -h      Pokaz pomoc.

Sciezki wzgledne sa liczone od korzenia projektu; domyslny folder to ".".
Pomijane sa ukryte wpisy, dowiazania symboliczne, node_modules oraz
glowne katalogi bin/ i scripts/. Korzen projektu odpowiada ~/public_html/.
Skrypt nie zapisuje poza projektem.
Plik .noindex chroni caly katalog i jego podkatalogi. Link do niego zostaje
w spisie rodzica. Strona dh/index.html wymaga znacznikow DYNAMIC_LINKS_START
i DYNAMIC_LINKS_END; zmieniana jest tylko zawartosc pomiedzy nimi.
HELP
}

is_public_directory() {
    local relative="${1#"$PROJECT_ROOT"}"
    relative="${relative#/}"
    case "/$relative/" in
        */.*/*|*/node_modules/*) return 1 ;;
    esac
    case "$relative" in
        bin|bin/*|scripts|scripts/*) return 1 ;;
    esac
    return 0
}

resolve_project_path() {
    local remaining="$1" normalized='' component cursor relative
    [[ "$remaining" == /* ]] || remaining="$PROJECT_ROOT/$remaining"
    while [[ -n "$remaining" ]]; do
        component="${remaining%%/*}"
        if [[ "$remaining" == */* ]]; then
            remaining="${remaining#*/}"
        else
            remaining=''
        fi
        case "$component" in
            ''|.) ;;
            ..) normalized="${normalized%/*}" ;;
            *) normalized="$normalized/$component" ;;
        esac
    done
    case "$normalized" in
        "$PROJECT_ROOT"|"$PROJECT_ROOT"/*) ;;
        *) die "Folder musi znajdowac sie w projekcie: $1" ;;
    esac
    cursor="$PROJECT_ROOT"
    relative="${normalized#"$PROJECT_ROOT"}"
    relative="${relative#/}"
    while [[ -n "$relative" ]]; do
        component="${relative%%/*}"
        if [[ "$relative" == */* ]]; then
            relative="${relative#*/}"
        else
            relative=''
        fi
        cursor="$cursor/$component"
        [[ ! -L "$cursor" ]] || die "Dowiazania symboliczne nie sa obslugiwane: $cursor"
        if [[ -e "$cursor" && ! -d "$cursor" ]]; then
            die "Sciezka nie jest katalogiem: $cursor"
        fi
    done
    RESOLVED_PATH="$normalized"
}

is_excluded_directory() {
    local directory="$1" excluded current="$1"
    if ((${#EXCLUDED_DIRS[@]} > 0)); then
        for excluded in "${EXCLUDED_DIRS[@]}"; do
            case "$directory" in
                "$excluded"|"$excluded"/*) return 0 ;;
            esac
        done
    fi
    while :; do
        if [[ -e "$current/.noindex" || -L "$current/.noindex" ]]; then
            return 0
        fi
        [[ "$current" != "$PROJECT_ROOT" ]] || break
        current="${current%/*}"
    done
    return 1
}

html_escape() {
    local value="$1"
    # Quoting the entire expansion preserves unwanted backslashes in Bash 3.2.
    value=${value//&/\&amp;}
    value=${value//</\&lt;}
    value=${value//>/\&gt;}
    value=${value//\"/\&quot;}
    value=${value//\'/\&#39;}
    value=${value//$'\n'/\&#10;}
    value=${value//$'\r'/\&#13;}
    value=${value//$'\t'/\&#9;}
    printf '%s' "$value"
}

url_encode() {
    local value="$1" result='' character encoded byte i
    for ((i = 0; i < ${#value}; i++)); do
        character="${value:i:1}"
        case "$character" in
            [a-zA-Z0-9.~_-]) result="$result$character" ;;
            *)
                # Bash 3.2 can report UTF-8 bytes as signed integers.
                printf -v byte '%d' "'$character"
                printf -v encoded '%%%02X' "$((byte & 255))"
                result="$result$encoded"
                ;;
        esac
    done
    printf '%s' "$result"
}

file_size() {
    if [[ "$STAT_STYLE" == gnu ]]; then
        stat -c '%s' -- "$1"
    else
        stat -f '%z' "$1"
    fi
}

format_size() {
    awk -v bytes="$1" 'BEGIN {
        split("B KB MB GB TB PB EB", units, " ");
        unit = 1;
        while (bytes >= 1000 && unit < 7) { bytes /= 1000; unit++; }
        if (unit > 1 && bytes >= 999.95 && unit < 7) { bytes /= 1000; unit++; }
        if (unit == 1) printf "%.0f %s", bytes, units[unit];
        else printf "%.1f %s", bytes, units[unit];
    }'
}

collect_directories() {
    local directory="$1" entry
    if is_excluded_directory "$directory"; then
        printf 'Pominieto chroniony katalog: %s\n' "$directory"
        return
    fi
    [[ -r "$directory" && -x "$directory" ]] || die "Nie mozna odczytac katalogu: $directory"
    DIRECTORIES+=("$directory")
    for entry in "$directory"/*; do
        [[ -d "$entry" && ! -L "$entry" ]] || continue
        is_public_directory "$entry" || continue
        collect_directories "$entry"
    done
}

validate_homepage() {
    local output="$1" line='' state=before
    while IFS= read -r line || [[ -n "$line" ]]; do
        if [[ "$line" =~ $LINKS_START_PATTERN ]]; then
            [[ "$state" == before ]] || die "Powtorzony lub niepoprawny DYNAMIC_LINKS_START: $output"
            state=inside
        elif [[ "$line" =~ $LINKS_END_PATTERN ]]; then
            [[ "$state" == inside ]] || die "Powtorzony lub niepoprawny DYNAMIC_LINKS_END: $output"
            state=after
        fi
    done < "$output"
    [[ "$state" == after ]] || die "Strona glowna wymaga jednej uporzadkowanej pary znacznikow DYNAMIC_LINKS_START / DYNAMIC_LINKS_END: $output"
}

validate_output() {
    local directory="$1" output="$1/index.html"
    if [[ -d "$directory" ]]; then
        [[ -r "$directory" && -w "$directory" && -x "$directory" ]] ||
            die "Brak uprawnien do katalogu: $directory"
    fi
    [[ ! -L "$output" ]] || die "Plik index.html jest dowiazaniem: $output"
    if [[ -e "$output" ]]; then
        [[ -f "$output" && -r "$output" ]] || die "Nie mozna odczytac pliku: $output"
    fi
    if [[ "$directory" == "$PERSONAL_ROOT" ]]; then
        [[ -f "$output" ]] || die "Brak osobistej strony glownej: $output. Przywroc plik ze znacznikami DYNAMIC_LINKS."
        validate_homepage "$output"
    elif [[ -f "$output" && "$FORCE" == false ]] && ! grep -Fqx -- "$MARKER" "$output"; then
        die "Chroniony index.html: $output. Dodaj .noindex, uzyj --exclude lub swiadomie zastap plik przez --force."
    fi
}

render_entries() {
    local directory="$1" include_files="$2" entry name bytes size_label
    ENTRY_COUNT=0
    for entry in "$directory"/*; do
        [[ -d "$entry" && ! -L "$entry" ]] || continue
        is_public_directory "$entry" || continue
        name="${entry##*/}"
        printf '            <li class="dir-item" data-entry><a class="entry-name is-folder" href="./%s/"><strong>%s/</strong></a></li>\n' \
            "$(url_encode "$name")" "$(html_escape "$name")"
        ENTRY_COUNT=$((ENTRY_COUNT + 1))
    done
    [[ "$include_files" == true ]] || return 0
    for entry in "$directory"/*; do
        [[ -f "$entry" && ! -L "$entry" ]] || continue
        name="${entry##*/}"
        [[ "$name" != index.html ]] || continue
        [[ "$entry" != "$PROJECT_ROOT"/dh/bazy-danych/*/autoryzacja.php && "$entry" != "$PROJECT_ROOT/dh/bazy-danych/autoryzacja.php" ]] || continue
        bytes="$(file_size "$entry")"
        size_label="$(format_size "$bytes")"
        printf '            <li class="dir-item" data-entry><a class="entry-name" href="./%s">%s</a><span class="file-size" data-bytes="%s" title="%s B">%s</span></li>\n' \
            "$(url_encode "$name")" "$(html_escape "$name")" "$bytes" "$bytes" "$size_label"
        ENTRY_COUNT=$((ENTRY_COUNT + 1))
    done
}

render_homepage() {
    local line='' ending inside=false
    # Preserve bytes outside the markers, including CRLF and a missing final newline.
    while :; do
        ending=''
        if IFS= read -r line; then
            ending=$'\n'
        elif [[ -z "$line" ]]; then
            break
        fi
        if [[ "$line" =~ $LINKS_START_PATTERN ]]; then
            printf '%s%s' "$line" "$ending"
            render_entries "$PERSONAL_ROOT" true
            inside=true
        elif [[ "$line" =~ $LINKS_END_PATTERN ]]; then
            inside=false
            printf '%s%s' "$line" "$ending"
        elif [[ "$inside" == false ]]; then
            printf '%s%s' "$line" "$ending"
        fi
    done < "$PERSONAL_ROOT/index.html"
}

